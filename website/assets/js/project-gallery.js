const galleries = document.querySelectorAll("[data-project-gallery]");
const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

const formatCaption = (index) => `Снимка ${index + 1}`;

galleries.forEach((gallery) => {
  const currentSlug = gallery.dataset.currentProject;
  const project = projectGalleries[currentSlug];

  if (!project || !project.images.length) {
    gallery.hidden = true;
    return;
  }

  const assetRoot = gallery.dataset.assetRoot || `../assets/images/projects/${currentSlug}/`;
  let activeIndex = 0;
  let isPlaying = !prefersReducedMotion && project.images.length > 1;
  let intervalId;

  gallery.innerHTML = `
    <div class="case-gallery-heading">
      <div>
        <p class="eyebrow">ГАЛЕРИЯ НА ПРОЕКТА</p>
        <h2>Галерия на ${project.title}</h2>
        <p>Снимки от реалните екрани на проекта: основни страници, администраторски панели, форми и работни потоци.</p>
      </div>
      <div class="gallery-controls" aria-label="Контроли за галерията">
        <button class="gallery-control" type="button" aria-label="Предишна снимка" data-gallery-prev>←</button>
        <button class="gallery-control gallery-play" type="button" aria-label="${isPlaying ? "Пауза на слайдшоуто" : "Стартирай слайдшоуто"}" data-gallery-toggle>${isPlaying ? "Пауза" : "Старт"}</button>
        <button class="gallery-control" type="button" aria-label="Следваща снимка" data-gallery-next>→</button>
      </div>
    </div>
    <div class="gallery-shell">
      <div class="gallery-stage">
        <a class="gallery-main-link" href="#" target="_blank" rel="noopener" data-gallery-link>
          <img src="" alt="" data-gallery-image>
        </a>
        <div class="gallery-caption">
          <div>
            <span data-gallery-sector></span>
            <strong data-gallery-title></strong>
          </div>
          <p data-gallery-counter></p>
        </div>
      </div>
      <div class="gallery-thumbs" role="list" aria-label="Снимки от ${project.title}" data-gallery-thumbs></div>
    </div>
  `;

  const image = gallery.querySelector("[data-gallery-image]");
  const link = gallery.querySelector("[data-gallery-link]");
  const title = gallery.querySelector("[data-gallery-title]");
  const sector = gallery.querySelector("[data-gallery-sector]");
  const counter = gallery.querySelector("[data-gallery-counter]");
  const thumbs = gallery.querySelector("[data-gallery-thumbs]");
  const previousButton = gallery.querySelector("[data-gallery-prev]");
  const nextButton = gallery.querySelector("[data-gallery-next]");
  const toggleButton = gallery.querySelector("[data-gallery-toggle]");

  if (project.images.length < 2) {
    previousButton.disabled = true;
    nextButton.disabled = true;
    toggleButton.disabled = true;
  }

  const getImageSource = (fileName) => `${assetRoot}${fileName}`;

  const renderThumbs = () => {
    thumbs.innerHTML = project.images
      .map((fileName, index) => {
        const caption = formatCaption(index);

        return `
          <button class="gallery-thumb" type="button" data-gallery-thumb="${index}" aria-label="Покажи ${caption}">
            <img src="${getImageSource(fileName)}" alt="" loading="lazy">
            <span>${caption}</span>
          </button>
        `;
      })
      .join("");
  };

  const updateGallery = (index) => {
    activeIndex = (index + project.images.length) % project.images.length;
    const fileName = project.images[activeIndex];
    const caption = formatCaption(activeIndex);
    const source = getImageSource(fileName);

    image.src = source;
    image.alt = `${project.title}: ${caption}`;
    link.href = source;
    link.setAttribute("aria-label", `Отвори ${caption} в пълен размер`);
    title.textContent = caption;
    sector.textContent = project.sector;
    counter.textContent = `${activeIndex + 1} / ${project.images.length}`;

    gallery.querySelectorAll("[data-gallery-thumb]").forEach((thumb, thumbIndex) => {
      const isActive = thumbIndex === activeIndex;

      thumb.classList.toggle("is-active", isActive);
      thumb.setAttribute("aria-current", isActive ? "true" : "false");
    });
  };

  const stopSlideshow = () => {
    window.clearInterval(intervalId);
    intervalId = undefined;
  };

  const startSlideshow = () => {
    stopSlideshow();

    if (!isPlaying || project.images.length < 2) {
      return;
    }

    intervalId = window.setInterval(() => updateGallery(activeIndex + 1), 5200);
  };

  previousButton.addEventListener("click", () => {
    updateGallery(activeIndex - 1);
    startSlideshow();
  });

  nextButton.addEventListener("click", () => {
    updateGallery(activeIndex + 1);
    startSlideshow();
  });

  toggleButton.addEventListener("click", () => {
    isPlaying = !isPlaying;
    toggleButton.textContent = isPlaying ? "Пауза" : "Старт";
    toggleButton.setAttribute("aria-label", isPlaying ? "Пауза на слайдшоуто" : "Стартирай слайдшоуто");
    startSlideshow();
  });

  gallery.addEventListener("click", (event) => {
    if (!(event.target instanceof Element)) {
      return;
    }

    const thumb = event.target.closest("[data-gallery-thumb]");

    if (!thumb) {
      return;
    }

    updateGallery(Number(thumb.dataset.galleryThumb));
    startSlideshow();
  });

  gallery.addEventListener("mouseenter", stopSlideshow);
  gallery.addEventListener("mouseleave", startSlideshow);
  gallery.addEventListener("focusin", stopSlideshow);
  gallery.addEventListener("focusout", startSlideshow);

  renderThumbs();
  updateGallery(activeIndex);
  startSlideshow();
});
